import json
import pytest
from evaluator import load_dataset, export_json, export_csv, evaluate_dataset, EvaluationError
from schemas import DatasetRow
from judge import LLMJudge, JudgeError
from ollama_client import OllamaError

class FakeClient:
    def __init__(self, responses=None, models=None, error=None):
        self.responses = responses or []
        self.models = models or ["target:latest", "judge:latest"]
        self.error = error
        self.calls = 0
    def list_models(self):
        if self.error: raise self.error
        return self.models
    def generate(self, model, prompt, json_mode=False, temperature=0):
        if self.error: raise self.error
        self.calls += 1
        if model == "target:latest": return "generated answer"
        if not self.responses: return json.dumps({"score": .9, "reason": "Supported", "evidence": ["evidence"]})
        return self.responses.pop(0)

def test_missing_expected_and_context_mark_metrics_unavailable():
    rows = [DatasetRow(question="Question?", actual_answer="An answer")]
    results = evaluate_dataset(rows, target_model="provided-answers", judge_model="judge:latest", client=FakeClient())
    metrics = results[0]["metrics"]
    assert metrics["answer_correctness"]["status"] == "N/A"
    assert metrics["faithfulness"]["status"] == "N/A"
    assert metrics["hallucination_risk"]["status"] == "N/A"
    assert metrics["answer_relevance"]["status"] == "PASS"

def test_malformed_judge_response_limited_retry():
    fake = FakeClient(responses=["not json", "still not json"])
    with pytest.raises(JudgeError, match="Could not parse"):
        LLMJudge(fake, "judge:latest", retries=1).evaluate(question="q", actual_answer="a", expected_answer="e", context=None, metric="answer_correctness", rubric="rubric")

def test_ollama_unavailable_is_not_swallowed():
    fake = FakeClient(error=OllamaError("server down"))
    with pytest.raises(Exception):
        evaluate_dataset([DatasetRow(question="q", actual_answer="a")], target_model="provided-answers", judge_model="judge:latest", client=fake)

def test_dataset_loading_and_exports(tmp_path):
    p = tmp_path / "data.csv"
    p.write_text('question,actual_answer\n"What?","This."\n', encoding="utf-8")
    rows = load_dataset(p)
    assert rows[0].actual_answer == "This."
    results = evaluate_dataset(rows, target_model="provided-answers", judge_model="judge:latest", client=FakeClient())
    assert '"summary"' in export_json(results)
    assert "metric_key" in export_csv(results)

def test_dataset_missing_file():
    with pytest.raises(EvaluationError, match="not found"):
        load_dataset("does-not-exist.csv")


def test_evaluate_dataset_calls_custom_python_model(monkeypatch):
    from types import SimpleNamespace
    from minieval import evaluator
    from minieval.schemas import DatasetRow

    seen = []
    def custom_model(question):
        seen.append(question)
        return "Generated by my model"

    class FakeJudge:
        def __init__(self, client, model):
            pass
        def evaluate(self, **kwargs):
            return SimpleNamespace(score=0.9, reason="Looks good", evidence=["test evidence"], execution_time_seconds=0.01)

    monkeypatch.setattr(evaluator, "LLMJudge", FakeJudge)
    rows = [DatasetRow(question="What is 2+2?", expected_answer="4", context="2+2 equals 4.")]
    results = evaluator.evaluate_dataset(
        rows, target_model="custom_python_model", judge_model="judge",
        client=object(), model_callable=custom_model,
    )
    assert seen == ["What is 2+2?"]
    assert results[0]["actual_answer"] == "Generated by my model"
    assert results[0]["generation_time_seconds"] is not None
    assert set(results[0]["metrics"]) == {"answer_correctness", "answer_relevance", "faithfulness", "hallucination_risk"}
